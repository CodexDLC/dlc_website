_PATTERN = re.compile(
    r"(?<![\w])(?:" + "|".join(re.escape(key) for key in sorted(PHRASES, key=len, reverse=True)) + r")(?![\w])",
    re.IGNORECASE,
)
_LOWER_PHRASES = {key.casefold(): value for key, value in PHRASES.items()}
_TECHNICAL_WORDS = {
    "ac", "cat", "classic", "dc", "hpas", "hv", "k", "nh", "pe", "pv", "rs",
    "se", "spd", "solaredge", "u", "uv", "wr", "wöhner", "x",
}


def translate_description(description: str) -> str | None:
    """Prepare a complete seed translation, rejecting unknown Latin words.

    Known electrical abbreviations, product names and measurements survive.
    An unknown German phrase or an address requires a reviewed stored pair;
    it must not silently become a partially translated Russian name.
    """
    translated = _PATTERN.sub(lambda match: _LOWER_PHRASES[match.group().casefold()], description)
    remaining_words = re.findall(r"[A-Za-zÄÖÜäöüß]+", translated)
    if any(word.casefold() not in _TECHNICAL_WORDS for word in remaining_words):
        return None
    return translated
